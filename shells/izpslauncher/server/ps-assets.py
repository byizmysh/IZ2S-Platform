im=Image.new('L',(1024,2048));d=ImageDraw.Draw(im);y=0;lines=[]
for key,text,size,face in labels:
 f=ImageFont.truetype(face,size);b=d.textbbox((0,0),text,font=f);w,h=b[2]-b[0],b[3]-b[1]
 if y+h+4>=2048:raise ValueError('Type atlas full')
 d.text((-b[0],y-b[1]),text,font=f,fill=255)
 lines.append(f'const ivec4 PS_{key}=ivec4(0,{y},{w},{h});');y+=h+10
# The progress card uses proportional type instead of the search keyboard's
# fixed-width glyph cells. Both weights fit in the existing reserved atlas.
y,progress_header=progress_type(d,y)
if y>2048:raise ValueError('Progress typography exceeds the shell atlas')
(root/'app/shaders/load-progress-type.glsl').write_text(progress_header)
pixels=im.tobytes();packed=bytearray(len(pixels)//4)
for n,v in enumerate(pixels):packed[n//4]|=((v*3+127)//255)<<((n%4)*2)
# Original UI type is used by module overlays and search keyboard.
source=root.parent/'izlauncher/app/assets'
original=zlib.decompress((source/'focus-type.deflate').read_bytes())
combined=bytearray(0x60000-65536+len(packed));combined[:len(original)]=original;combined[0x60000-65536:]=packed
(root/'app/assets/focus-type.deflate').write_bytes(zlib.compress(combined,9))
(root/'app/assets/focus-type.json').write_text(json.dumps(dict(width=768,height=1172,bytes=len(combined),offset=65536)))
(root/'app/shaders/ps-text.glsl').write_text('// Generated by server/ps-assets.py.\n'+ '\n'.join(lines)+'\n')
(root/'preview').mkdir(exist_ok=True)
im.save(root/'preview/typography.png')
print('IZPS type atlas:',y,'rows,',len(combined),'bytes')
